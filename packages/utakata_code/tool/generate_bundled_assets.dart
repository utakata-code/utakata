// 実行時に読む同梱ファイルを lib/src/bundled_assets.g.dart の const に埋め込む
// (Issue #36)。`dart compile exe` で作った実行ファイルでは
// Isolate.resolvePackageUri がパッケージの場所を返さないため、
// その場合は埋め込んだ中身を ~/.utakata/cache/bundled-<版>/ に書き出して使う。
//
// 実行: dart run tool/generate_bundled_assets.dart (packages/utakata_code で)
//
// 次のファイルを変えたら必ず再生成する(test/bundled_assets_test.dart が
// 中身の一致を確かめる):
//   - lib/src/0_templates/**   (tool/sync_arch_lib.dart の同期後も)
//   - doc/*.md                 (`utakata doc show` が読む。doc/skills/ は
//                               実行時に読まないので含めない)
//
// 書き出し先を差し替えたいときは環境変数 UTAKATA_ASSETS_DIR に
// パッケージルートと同じ並び(lib/src/0_templates, doc)のディレクトリを指定する。
import 'dart:convert';
import 'dart:io';

const outputPath = 'lib/src/bundled_assets.g.dart';

/// [packageRoot] から埋め込み対象を集める(キーはパッケージルート相対・`/` 区切り)。
Map<String, String> collectBundledAssets(String packageRoot) {
  final result = <String, String>{};

  void addFile(File file) {
    final rel = file.path
        .substring(packageRoot.length)
        .replaceAll(Platform.pathSeparator, '/')
        .replaceFirst(RegExp('^/+'), '');
    final name = rel.split('/').last;
    if (name.startsWith('.')) return;
    result[rel] = file.readAsStringSync();
  }

  final templates = Directory('$packageRoot/lib/src/0_templates');
  for (final f in templates.listSync(recursive: true).whereType<File>()) {
    addFile(f);
  }

  final doc = Directory('$packageRoot/doc');
  for (final f in doc.listSync().whereType<File>()) {
    if (f.path.endsWith('.md')) addFile(f);
  }

  final keys = result.keys.toList()..sort();
  return {for (final k in keys) k: result[k]!};
}

/// Dart の文字列リテラルにする(`$` の補間を止める)。
String _literal(String s) => jsonEncode(s).replaceAll(r'$', r'\$');

/// 生成ファイルの中身を返す(テストからも使う)。
String renderBundledAssets(String packageRoot) {
  final assets = collectBundledAssets(packageRoot);
  final buffer = StringBuffer()
    ..writeln('// GENERATED FILE — DO NOT EDIT.')
    ..writeln('// Generated by tool/generate_bundled_assets.dart from')
    ..writeln('// lib/src/0_templates/** and doc/*.md.')
    ..writeln()
    ..writeln('/// パッケージルート相対パス → ファイル内容。')
    ..writeln('const Map<String, String> bundledAssets = <String, String>{');
  for (final entry in assets.entries) {
    buffer.writeln('  ${_literal(entry.key)}:');
    // 1 行ずつ隣接リテラルにして差分を読みやすくする。
    final lines = entry.value.split('\n');
    final parts = <String>[
      for (var i = 0; i < lines.length; i++)
        i < lines.length - 1 ? '${lines[i]}\n' : lines[i],
    ]..removeWhere((s) => s.isEmpty);
    if (parts.isEmpty) parts.add('');
    for (var i = 0; i < parts.length; i++) {
      final suffix = i == parts.length - 1 ? ',' : '';
      buffer.writeln('      ${_literal(parts[i])}$suffix');
    }
  }
  buffer.writeln('};');
  return buffer.toString();
}

void main() {
  if (!Directory('lib/src/0_templates').existsSync()) {
    stderr.writeln('run from packages/utakata_code (missing lib/src/0_templates)');
    exit(66);
  }
  final root = Directory.current.path;
  final content = renderBundledAssets(root);
  final outFile = File(outputPath);
  outFile.writeAsStringSync(content);
  final count = collectBundledAssets(root).length;
  stdout.writeln('Wrote ${outFile.path} ($count files, ${content.length} chars)');
}
